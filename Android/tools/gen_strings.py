#!/usr/bin/env python3
"""Generate app string resources from the web app's TRANSLATIONS table.

Run from Android/:  python3 tools/gen_strings.py
Keeps wording identical to the website; app-only strings live in extra_strings.json.
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_PREFIXES = (
    "intro_", "privacy", "license", "codex_", "noto_", "flaticon", "icon_", "push_", "first_visit",
    "updates", "update_", "court_info", "hall_search", "hall_api", "contact_method", "contact_email",
    "contact_website", "contact_discord", "contact_line", "contact_telegram", "contact_unconfigured",
    "contact_operator", "shuttlecock_icon", "source_page", "font_", "development_", "footer",
    "invalid_csrf", "current_section", "jump_to_section", "export_all", "admin_logout", "android_page",
)
# Web strings under a skipped prefix that the app still uses verbatim.
KEEP = {
    "push_notifications", "push_notifications_body", "push_notifications_toggle",
    "push_notifications_enabled", "push_notifications_disabled", "push_notifications_error",
}
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def load_web():
    src = (ROOT.parent / "Web" / "app.py").read_text(encoding="utf-8")
    start = src.index("TRANSLATIONS = {")
    end = src.index("\n}\n", start) + 2
    return ast.literal_eval(src[start + len("TRANSLATIONS = "):end])


def escape(text: str) -> str:
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def convert(text: str) -> tuple[str, bool]:
    names = []

    def sub(match):
        if match.group(1) not in names:
            names.append(match.group(1))
        return f"%{names.index(match.group(1)) + 1}$s"

    converted = PLACEHOLDER.sub(sub, text)
    has_format = bool(names) or bool(re.search(r"%\d\$[sd]", text))
    if not has_format:
        converted = converted.replace("%", "%%") if "%" in converted else converted
    return converted, has_format


def write(path: Path, entries: dict[str, str]):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py. Do not edit. -->", "<resources>"]
    for key in sorted(entries):
        value, _ = convert(entries[key])
        lines.append(f'    <string name="{key}">{escape(value)}</string>')
    lines.append("</resources>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    web = load_web()
    extra = json.loads((ROOT / "tools" / "extra_strings.json").read_text(encoding="utf-8"))
    en, zh = {}, {}
    for key, value in web["en-us"].items():
        if key.startswith(SKIP_PREFIXES) and key not in KEEP:
            continue
        en[key] = value
        zh[key] = web["zh-tw"].get(key, value)
    for key, (english, chinese) in extra.items():
        en[key], zh[key] = english, chinese
    res = ROOT / "app" / "src" / "main" / "res"
    write(res / "values" / "strings.xml", en)
    write(res / "values-zh-rTW" / "strings.xml", zh)
    print(f"{len(en)} strings")


if __name__ == "__main__":
    main()
